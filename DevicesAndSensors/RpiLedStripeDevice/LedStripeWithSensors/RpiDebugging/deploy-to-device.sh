#!/usr/bin/env bash
# Builds LedStripeWithSensors for the Raspberry Pi (linux-arm64), copies it over SSH and (re)starts it.
# Replaces the old runAndDebugRemotely.ps1.
#
#   ./deploy-to-device.sh                  # build, deploy, restart in the background
#   ./deploy-to-device.sh --foreground     # ... and stay attached to the app's output (Ctrl+C stops it)
#   ./deploy-to-device.sh --host 192.168.8.67 --user mciec
#
# One-time setup - passwordless SSH from this machine:
#   ssh-keygen -t ed25519 -N "" -f ~/.ssh/id_ed25519        (skip if you already have a key)
#   ssh-copy-id mciec@192.168.8.20
#
# MQTT: the app connects to the broker inside the HomeControl container as user "raspberry" (see
# MqttConfig in appSettings.json). Its password is the Broker:DevicePassword user secret (generated by
# deploy-azure-aca.sh), or DEVICE_PASSWORD from the environment. It is written to the Pi in a private
# run script (~/runLedStripeWithSensors.sh, mode 700 - the script the @reboot cron entry already uses),
# never into the repo or appSettings.json.
set -euo pipefail

HOST="${RPI_HOST:-192.168.8.20}"; RPI_USER="${RPI_USER:-mciec}"; FOREGROUND=0
while [ $# -gt 0 ]; do
  case "$1" in
    --host) HOST="$2"; shift 2 ;;
    --user) RPI_USER="$2"; shift 2 ;;
    --foreground) FOREGROUND=1; shift ;;
    -h|--help) sed -n '2,/^set -euo/p' "$0" | sed '$d;s/^# \{0,1\}//'; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="$HERE/../LedStripeWithSensors.csproj"
PUBLISH_DIR="$HERE/../bin/Debug/net10.0/publish/linux-arm64"
USER_SECRETS_ID="1c8133fb-92ec-49d1-8df3-ea9190fbddff"
REMOTE="$RPI_USER@$HOST"
APP_DIR="projects/LedStripeWithSensors"      # relative to the Pi user's home
SSH_OPTS=(-o BatchMode=yes -o ConnectTimeout=8 -o StrictHostKeyChecking=accept-new)
rssh() { ssh "${SSH_OPTS[@]}" "$REMOTE" "$@"; }

echo "RPI: $REMOTE"
if ! rssh true 2>/dev/null; then
  echo "Cannot log in to $REMOTE without a password. Install this machine's key first:" >&2
  echo "  ssh-copy-id $REMOTE" >&2
  exit 1
fi

DEVICE_PASSWORD="${DEVICE_PASSWORD:-$(dotnet user-secrets --id "$USER_SECRETS_ID" list 2>/dev/null | sed -n 's/^Broker:DevicePassword = //p')}"
if [ -z "$DEVICE_PASSWORD" ]; then
  echo "No broker password: set the Broker:DevicePassword user secret or DEVICE_PASSWORD." >&2
  exit 1
fi

echo "Building and publishing for linux-arm64..."
dotnet publish "$PROJECT" -p:PublishProfile=FolderProfile -v q --nologo >/dev/null \
  || { echo "Publish failed, aborting deployment." >&2; exit 1; }

echo "Stopping the running app and clearing the old files (logs are kept)..."
# [L] keeps pkill from matching this very command line.
rssh "pkill -f '[L]edStripeWithSensors.dll' || true; mkdir -p ~/$APP_DIR; find ~/$APP_DIR -mindepth 1 -maxdepth 1 ! -name logs -exec rm -rf {} +"
echo "Copying the new build..."
scp -q -r "$PUBLISH_DIR"/* "$REMOTE:$APP_DIR/"

echo "Installing the run script (holds the broker password)..."
rssh "umask 077; cat > ~/runLedStripeWithSensors.sh" <<RUN
#!/bin/sh
export DOTNET_LEDSTRIPEWITHSENSORS_MqttConfig__Password='$DEVICE_PASSWORD'
cd ~/$APP_DIR
exec ~/.dotnet/dotnet LedStripeWithSensors.dll
RUN
rssh "chmod 700 ~/runLedStripeWithSensors.sh"

if [ "$FOREGROUND" = "1" ]; then
  echo "Running (Ctrl+C to stop)..."
  exec ssh -t "${SSH_OPTS[@]}" "$REMOTE" "sh ~/runLedStripeWithSensors.sh"
fi
rssh "nohup sh ~/runLedStripeWithSensors.sh > ~/$APP_DIR/run.log 2>&1 < /dev/null &"
sleep 4
echo "--- ~/$APP_DIR/run.log"
rssh "tail -n 15 ~/$APP_DIR/run.log; pgrep -f '[L]edStripeWithSensors.dll' >/dev/null && echo '[running]' || echo '[NOT running]'"
echo "Crontab @reboot entry:"; rssh "crontab -l 2>/dev/null | grep -F runLedStripeWithSensors || echo '  (none - add: @reboot sh /home/$RPI_USER/runLedStripeWithSensors.sh)'"
